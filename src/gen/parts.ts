export function partsFor(layer: Layer, version: number, secret: boolean): PartDef[] {
  return PARTS[layer].filter((p) => p.since <= version && (!p.secretOnly || secret));
}

export function partById(layer: Layer, id: string): PartDef | undefined {
  return PARTS[layer].find((p) => p.id === id);
}

export function partName(layer: Layer, id: string): string {
  return partById(layer, id)?.name ?? id;
}

/** All tags that appear anywhere (for orders and sets). */
export function allTags(version: number): Set<string> {
  const s = new Set<string>();
  for (const layer of Object.keys(PARTS) as Layer[]) for (const p of partsFor(layer, version, true)) p.tags.forEach((t) => s.add(t));
  return s;
}
